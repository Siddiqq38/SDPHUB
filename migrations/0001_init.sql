CREATE EXTENSION IF NOT EXISTS citext;

-- SDP Tigalapan Operations System: skema awal (Postgres / Supabase)
-- Semua waktu disimpan sebagai epoch milidetik UTC (BIGINT). Tampilan memakai WITA.
-- Kode/nomor disimpan sebagai TEXT agar nol di depan tidak hilang.

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      CITEXT NOT NULL UNIQUE,
  pass_hash     TEXT NOT NULL,
  pass_salt     TEXT NOT NULL,
  pass_iter     BIGINT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('master','supervisor','cs','crm','operator','gudang','qc','fat','customer')),
  active        BIGINT NOT NULL DEFAULT 1,
  must_change_password BIGINT NOT NULL DEFAULT 1,
  customer_id   BIGINT,
  session_epoch BIGINT NOT NULL DEFAULT 0,
  created_at    BIGINT NOT NULL
);

CREATE TABLE employees (
  user_id       BIGINT PRIMARY KEY REFERENCES users(id),
  reg_code      TEXT NOT NULL UNIQUE,
  full_name     TEXT NOT NULL,
  employee_no   TEXT NOT NULL,
  department    TEXT NOT NULL,
  job_title     TEXT NOT NULL
);

CREATE TABLE sessions (
  id            TEXT PRIMARY KEY,          -- hash SHA-256 dari token sesi
  user_id       BIGINT NOT NULL REFERENCES users(id),
  csrf          TEXT NOT NULL,
  epoch         BIGINT NOT NULL,
  created_at    BIGINT NOT NULL,
  expires_at    BIGINT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE login_attempts (
  key           TEXT NOT NULL,             -- username|ip
  at            BIGINT NOT NULL
);
CREATE INDEX idx_login_attempts ON login_attempts(key, at);

CREATE TABLE bootstrap (
  id            BIGINT PRIMARY KEY CHECK (id = 1),
  used_at       BIGINT
);
INSERT INTO bootstrap (id, used_at) VALUES (1, NULL);

CREATE TABLE customers (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          TEXT NOT NULL UNIQUE,
  business_name TEXT NOT NULL,
  pic_name      TEXT NOT NULL,
  contact       TEXT NOT NULL,
  email         TEXT,
  address       TEXT NOT NULL,
  business_type TEXT,
  city_scope    TEXT NOT NULL CHECK (city_scope IN ('in_city','out_city')),
  payment_policy TEXT NOT NULL DEFAULT 'belum_diatur',
  notes         TEXT,
  created_at    BIGINT NOT NULL
);

ALTER TABLE users ADD CONSTRAINT users_customer_fk FOREIGN KEY (customer_id) REFERENCES customers(id);

CREATE TABLE member_applications (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_name TEXT NOT NULL,
  pic_name      TEXT NOT NULL,
  contact       TEXT NOT NULL,
  email         TEXT,
  address       TEXT NOT NULL,
  business_type TEXT NOT NULL,
  city_scope    TEXT NOT NULL CHECK (city_scope IN ('in_city','out_city')),
  username      CITEXT NOT NULL,
  pass_hash     TEXT NOT NULL,
  pass_salt     TEXT NOT NULL,
  pass_iter     BIGINT NOT NULL,
  consent_contact BIGINT NOT NULL CHECK (consent_contact = 1),
  status        TEXT NOT NULL DEFAULT 'menunggu_cs'
                CHECK (status IN ('menunggu_cs','menunggu_survei','menunggu_acc','aktif','ditolak')),
  cs_note       TEXT, cs_by BIGINT REFERENCES users(id), cs_at BIGINT,
  crm_note      TEXT, crm_feasible BIGINT, crm_by BIGINT REFERENCES users(id), crm_at BIGINT,
  master_note   TEXT, master_by BIGINT REFERENCES users(id), master_at BIGINT,
  link_customer_id BIGINT REFERENCES customers(id),
  user_id       BIGINT REFERENCES users(id),
  source        TEXT NOT NULL DEFAULT 'online',  -- online | workshop
  created_at    BIGINT NOT NULL
);

-- Layanan dan norma: dikonfigurasi master, tidak ada nilai bawaan yang dikarang.
CREATE TABLE services (
  code          TEXT PRIMARY KEY,          -- DTF | SUBLIM_KERTAS | SUBLIM_KAIN
  family        TEXT NOT NULL CHECK (family IN ('DTF','SUBLIM')),
  name          TEXT NOT NULL,
  output_label  TEXT NOT NULL,             -- istilah untuk tracking publik
  active        BIGINT NOT NULL DEFAULT 1,
  stages_json   TEXT NOT NULL
);

CREATE TABLE machines (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          TEXT NOT NULL UNIQUE,
  name          TEXT NOT NULL,
  kind          TEXT NOT NULL CHECK (kind IN ('dtf_printer','sublim_printer','calender')),
  active        BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE norms (
  machine_kind  TEXT PRIMARY KEY,
  seconds_per_unit DOUBLE PRECISION,                   -- NULL = Belum diatur
  unit          TEXT NOT NULL DEFAULT 'meter',
  source_note   TEXT
);

CREATE TABLE settings (
  key           TEXT PRIMARY KEY,
  value         TEXT NOT NULL
);

CREATE TABLE attendance (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL REFERENCES users(id),
  day           TEXT NOT NULL,             -- YYYY-MM-DD WITA
  check_in_at   BIGINT NOT NULL,
  check_out_at  BIGINT,
  standby       BIGINT NOT NULL DEFAULT 0,
  UNIQUE (user_id, day)
);

CREATE TABLE orders (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no      TEXT NOT NULL UNIQUE,
  customer_id   BIGINT NOT NULL REFERENCES customers(id),
  po_ref        TEXT,
  end_customer_ref TEXT,                   -- opsional
  received_at   BIGINT NOT NULL,
  customer_deadline BIGINT,
  sdp_promise_at BIGINT,
  sdp_promise_prev_json TEXT NOT NULL DEFAULT '[]',
  priority      TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('rendah','normal','tinggi','urgent')),
  description   TEXT,
  packing_note  TEXT,
  handover_method TEXT,
  qc_requirements TEXT,
  notes         TEXT,
  status        TEXT NOT NULL DEFAULT 'menunggu_cs'
                CHECK (status IN ('menunggu_cs','menunggu_rilis','dirilis','berjalan','selesai_produksi','serah_terima_sebagian','selesai','dibatalkan')),
  cs_confirmed_detail BIGINT NOT NULL DEFAULT 0,
  cs_confirm_ref TEXT,
  cs_payment_checked BIGINT NOT NULL DEFAULT 0,
  cs_deadline_feasible BIGINT NOT NULL DEFAULT 0,
  cs_validation_note TEXT,
  cs_by         BIGINT REFERENCES users(id),
  cs_at         BIGINT,
  release_by    BIGINT REFERENCES users(id),
  release_at    BIGINT,
  closed_at     BIGINT,
  created_by    BIGINT NOT NULL REFERENCES users(id),
  created_at    BIGINT NOT NULL
);
CREATE INDEX idx_orders_customer ON orders(customer_id);

CREATE TABLE order_items (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT NOT NULL REFERENCES orders(id),
  service_code  TEXT NOT NULL REFERENCES services(code),
  description   TEXT,
  order_qty     DOUBLE PRECISION NOT NULL,
  order_unit    TEXT NOT NULL,             -- satuan pesanan
  prod_unit     TEXT NOT NULL,             -- satuan produksi
  bill_unit     TEXT NOT NULL,             -- satuan penagihan
  prod_per_order DOUBLE PRECISION,                     -- konversi eksplisit order->produksi
  bill_per_order DOUBLE PRECISION,                     -- konversi eksplisit order->tagih
  media_width_mm DOUBLE PRECISION,
  print_width_mm DOUBLE PRECISION,
  design_size   TEXT,
  material_type TEXT,
  material_owner TEXT NOT NULL DEFAULT 'sdp' CHECK (material_owner IN ('sdp','customer')),
  output_form   TEXT,
  approved_artwork_id BIGINT
);

CREATE TABLE artworks (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id       BIGINT NOT NULL REFERENCES order_items(id),
  version       BIGINT NOT NULL,
  file_key      TEXT NOT NULL,             -- kunci R2 privat
  file_name     TEXT NOT NULL,
  size_bytes    BIGINT NOT NULL,
  size_note     TEXT,
  preflight_status TEXT NOT NULL DEFAULT 'menunggu_file'
                CHECK (preflight_status IN ('menunggu_file','diperiksa','perlu_revisi','menunggu_persetujuan','disetujui')),
  preflight_note TEXT,
  preview_ref   TEXT,
  uploaded_by   BIGINT NOT NULL REFERENCES users(id),
  uploaded_at   BIGINT NOT NULL,
  approved_by_pic TEXT,
  approved_at   BIGINT,
  revision_impact_note TEXT,
  UNIQUE (item_id, version)
);

CREATE TABLE work_orders (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wo_no         TEXT NOT NULL UNIQUE,
  item_id       BIGINT NOT NULL REFERENCES order_items(id),
  order_id      BIGINT NOT NULL REFERENCES orders(id),
  stage         TEXT NOT NULL,             -- print_film, print_kertas, transfer_calender, dst.
  machine_id    BIGINT NOT NULL REFERENCES machines(id),
  artwork_id    BIGINT NOT NULL REFERENCES artworks(id),
  planned_qty   DOUBLE PRECISION NOT NULL,
  planned_unit  TEXT NOT NULL,
  assigned_to   BIGINT REFERENCES users(id),
  assigned_by   BIGINT REFERENCES users(id),
  queue_pos     BIGINT NOT NULL DEFAULT 0,
  status        TEXT NOT NULL DEFAULT 'menunggu'
                CHECK (status IN ('menunggu','berjalan','selesai','dibatalkan')),
  est_start_at  BIGINT, est_end_at BIGINT,          -- estimasi terkini
  est_initial_end_at BIGINT,                         -- baseline SLA, tidak ikut bergeser
  est_manual    BIGINT NOT NULL DEFAULT 0,
  started_at    BIGINT, started_by BIGINT REFERENCES users(id), started_session TEXT,
  finished_at   BIGINT,
  raw_duration_s BIGINT,
  effective_s   BIGINT,
  out_total     DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at    BIGINT NOT NULL
);
-- Satu mesin tidak boleh punya dua WO berjalan sekaligus (ditegakkan di DB).
CREATE UNIQUE INDEX idx_one_running_per_machine ON work_orders(machine_id) WHERE status = 'berjalan';

CREATE TABLE estimate_history (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wo_id         BIGINT NOT NULL REFERENCES work_orders(id),
  est_end_at    BIGINT,
  reason        TEXT NOT NULL,
  at            BIGINT NOT NULL,
  by_user       BIGINT REFERENCES users(id)
);

CREATE TABLE machine_qc_reports (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  machine_id    BIGINT NOT NULL REFERENCES machines(id),
  day           TEXT NOT NULL,
  checklist_json TEXT NOT NULL,            -- [{key,label,ok,photo_key?}]
  has_ng        BIGINT NOT NULL,
  finding       TEXT,
  action_note   TEXT,
  conclusion    TEXT NOT NULL CHECK (conclusion IN ('siap','tahan_produksi')),
  reported_by   BIGINT NOT NULL REFERENCES users(id),
  at            BIGINT NOT NULL
);
CREATE INDEX idx_mqc ON machine_qc_reports(machine_id, day, at);

CREATE TABLE qc_results (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wo_id         BIGINT NOT NULL REFERENCES work_orders(id),
  verdict       TEXT NOT NULL CHECK (verdict IN ('pass','hold','rework','reject')),
  qty_initial   DOUBLE PRECISION NOT NULL,             -- output awal
  qty_reject    DOUBLE PRECISION NOT NULL DEFAULT 0,
  qty_rework    DOUBLE PRECISION NOT NULL DEFAULT 0,
  qty_good_final DOUBLE PRECISION NOT NULL DEFAULT 0,  -- tidak dihitung ganda
  note          TEXT,
  by_user       BIGINT NOT NULL REFERENCES users(id),
  at            BIGINT NOT NULL
);

CREATE TABLE material_lots (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roll_id       TEXT NOT NULL UNIQUE,
  sku           TEXT NOT NULL,
  owner         TEXT NOT NULL CHECK (owner IN ('sdp','customer')),
  customer_id   BIGINT REFERENCES customers(id),
  unit          TEXT NOT NULL,
  declared_qty  DOUBLE PRECISION NOT NULL,
  measured_qty  DOUBLE PRECISION NOT NULL,
  diff_confirmed BIGINT NOT NULL DEFAULT 0,
  condition     TEXT,
  location      TEXT,
  status        TEXT NOT NULL DEFAULT 'tersedia',
  received_by   BIGINT NOT NULL REFERENCES users(id),
  received_at   BIGINT NOT NULL,
  photo_key     TEXT
);

-- Ledger idempotent per sumber: (source_type, source_id, kind) unik.
CREATE TABLE stock_ledger (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_id        BIGINT NOT NULL REFERENCES material_lots(id),
  kind          TEXT NOT NULL CHECK (kind IN ('receive','reserve','release_reserve','use','waste','return_stock','return_owner','sample','cleaning','maintenance')),
  qty           DOUBLE PRECISION NOT NULL,
  source_type   TEXT NOT NULL,
  source_id     TEXT NOT NULL,
  note          TEXT,
  at            BIGINT NOT NULL,
  by_user       BIGINT NOT NULL REFERENCES users(id),
  UNIQUE (source_type, source_id, kind)
);

CREATE TABLE tracking (
  code          TEXT PRIMARY KEY,          -- 128 bit acak, base64url
  order_id      BIGINT NOT NULL REFERENCES orders(id),
  courier_receipt TEXT,
  created_at    BIGINT NOT NULL
);

CREATE TABLE handovers (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT NOT NULL REFERENCES orders(id),
  item_id       BIGINT NOT NULL REFERENCES order_items(id),
  package_label TEXT NOT NULL,
  wo_id         BIGINT REFERENCES work_orders(id),
  qc_result_id  BIGINT REFERENCES qc_results(id),
  qty_good      DOUBLE PRECISION NOT NULL,
  qty_this      DOUBLE PRECISION NOT NULL,
  qty_cumulative DOUBLE PRECISION NOT NULL,
  remaining_result DOUBLE PRECISION NOT NULL,
  remaining_work DOUBLE PRECISION NOT NULL,
  material_returned TEXT,
  handed_by     BIGINT NOT NULL REFERENCES users(id),
  received_by_name TEXT NOT NULL,
  evidence_ref  TEXT,
  courier_receipt TEXT,
  at            BIGINT NOT NULL
);

CREATE TABLE invoices (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT NOT NULL REFERENCES orders(id),
  kind          TEXT NOT NULL CHECK (kind IN ('penawaran','dp','invoice')),
  amount        BIGINT NOT NULL,          -- rupiah, diisi manusia; tidak ada tarif bawaan
  due_at        BIGINT,
  note          TEXT,
  created_by    BIGINT NOT NULL REFERENCES users(id),
  created_at    BIGINT NOT NULL
);

CREATE TABLE payments (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT NOT NULL REFERENCES orders(id),
  invoice_id    BIGINT REFERENCES invoices(id),
  amount        BIGINT NOT NULL,
  proof_key     TEXT,
  proof_uploaded_by BIGINT REFERENCES users(id),
  proof_uploaded_at BIGINT,
  verified      BIGINT NOT NULL DEFAULT 0,   -- hanya FAT yang bisa 1
  verified_by   BIGINT REFERENCES users(id),
  verified_at   BIGINT,
  note          TEXT
);

CREATE TABLE complaints (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      BIGINT NOT NULL REFERENCES orders(id),
  wo_id         BIGINT REFERENCES work_orders(id),
  description   TEXT NOT NULL,
  evidence_key  TEXT,
  investigation TEXT,
  solution      TEXT,
  approved_by   BIGINT REFERENCES users(id),
  status        TEXT NOT NULL DEFAULT 'baru' CHECK (status IN ('baru','investigasi','solusi','selesai')),
  opened_by     BIGINT NOT NULL REFERENCES users(id),
  opened_at     BIGINT NOT NULL
);

CREATE TABLE loss_sales (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   BIGINT REFERENCES customers(id),
  reason        TEXT NOT NULL,
  potential_amount BIGINT,
  is_duplicate  BIGINT NOT NULL DEFAULT 0,   -- double input tidak dihitung
  by_user       BIGINT NOT NULL REFERENCES users(id),
  at            BIGINT NOT NULL
);

CREATE TABLE audit_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at            BIGINT NOT NULL,
  user_id       BIGINT,
  action        TEXT NOT NULL,
  entity        TEXT,
  entity_id     TEXT,
  detail        TEXT
);
