-- Inventory per roll / kemasan: GR, put away ke bin, dan kartu stok per lot.
CREATE TABLE bins (
  code       TEXT PRIMARY KEY,
  note       TEXT,
  created_at BIGINT NOT NULL
);

CREATE TABLE lots (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_code    TEXT NOT NULL UNIQUE,                -- ID roll / kemasan: batch-nomor urut
  sku_code    TEXT NOT NULL REFERENCES skus(code),
  batch       TEXT NOT NULL,
  qty_initial DOUBLE PRECISION NOT NULL CHECK (qty_initial > 0),
  qty_left    DOUBLE PRECISION NOT NULL CHECK (qty_left >= 0),
  bin         TEXT,
  status      TEXT NOT NULL CHECK (status IN ('menunggu','tersedia','habis')),
  supplier    TEXT NOT NULL,
  doc_no      TEXT,
  received_by TEXT NOT NULL,
  received_at BIGINT NOT NULL,
  putaway_by  TEXT,
  putaway_at  BIGINT,
  request_key TEXT                                 -- cegah GR ganda saat dikirim ulang
);
CREATE INDEX idx_lots_sku ON lots(sku_code, status);

ALTER TABLE stock_ledger ADD COLUMN lot_code TEXT;
ALTER TABLE stock_ledger ADD COLUMN note TEXT;
ALTER TABLE stock_ledger ADD COLUMN request_key TEXT;

ALTER TABLE bins ENABLE ROW LEVEL SECURITY;
ALTER TABLE lots ENABLE ROW LEVEL SECURITY;
