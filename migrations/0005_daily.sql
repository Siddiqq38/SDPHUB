-- Konfirmasi laporan harian per shift (pengganti laporan di grup WhatsApp).
CREATE TABLE shift_reports (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day     TEXT NOT NULL,
  shift   BIGINT NOT NULL CHECK (shift IN (1, 2)),
  service TEXT NOT NULL CHECK (service IN ('dtf','sub')),
  note    TEXT,
  by_user TEXT NOT NULL,
  at      BIGINT NOT NULL
);
CREATE INDEX idx_shift_reports_day ON shift_reports(day);
ALTER TABLE shift_reports ENABLE ROW LEVEL SECURITY;
