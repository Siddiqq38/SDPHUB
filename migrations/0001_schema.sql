-- SDP Print Hub (Postgres / Supabase): alur DTF dan Sublim sesuai WIC-OPR-005.
-- Waktu disimpan sebagai epoch milidetik (BIGINT); tampilan memakai WITA. Rupiah BIGINT.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          CITEXT NOT NULL UNIQUE,            -- kode pengguna untuk login
  name          TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('master','manager','spv','cs','crm','store','op','qc','gudang','fat')),
  store         TEXT,                              -- nama toko untuk Store Head
  active        BIGINT NOT NULL DEFAULT 1,
  pass_hash     TEXT NOT NULL,
  pass_salt     TEXT NOT NULL,
  pass_iter     BIGINT NOT NULL,
  must_change_password BIGINT NOT NULL DEFAULT 1,
  session_epoch BIGINT NOT NULL DEFAULT 0,
  created_at    BIGINT NOT NULL
);

CREATE TABLE sessions (
  id         TEXT PRIMARY KEY,                     -- hash SHA-256 token sesi
  user_id    BIGINT NOT NULL REFERENCES users(id),
  csrf       TEXT NOT NULL,
  epoch      BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE login_attempts (key TEXT NOT NULL, at BIGINT NOT NULL);
CREATE INDEX idx_login_attempts ON login_attempts(key, at);

CREATE TABLE bootstrap (id BIGINT PRIMARY KEY CHECK (id = 1), used_at BIGINT);
INSERT INTO bootstrap (id, used_at) VALUES (1, NULL);

CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE role_access (role TEXT PRIMARY KEY, pages TEXT NOT NULL);   -- JSON array nama menu

CREATE TABLE customers (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        TEXT NOT NULL UNIQUE,
  name        TEXT NOT NULL,
  wa          TEXT NOT NULL,
  source      TEXT NOT NULL CHECK (source IN ('Tigalapan Kaos','Customer baru')),
  status      TEXT NOT NULL CHECK (status IN ('aktif','menunggu','ditolak')),
  verified_by TEXT,
  verified_at BIGINT,
  created_at  BIGINT NOT NULL
);

CREATE TABLE orders (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no    TEXT NOT NULL UNIQUE,
  track_code  TEXT NOT NULL UNIQUE,                -- acak 128 bit, untuk lacak publik
  type        TEXT NOT NULL CHECK (type IN ('retail','maklon')),
  service     TEXT NOT NULL CHECK (service IN ('dtf','sub')),
  customer_id BIGINT REFERENCES customers(id),
  customer_name TEXT NOT NULL,
  wa          TEXT NOT NULL,
  source      TEXT NOT NULL CHECK (source IN ('WhatsApp','Datang langsung','Toko')),
  store       TEXT,
  items       TEXT NOT NULL,                       -- JSON: [{name,qty,unit,price,meter}], harga dihitung server
  meter       DOUBLE PRECISION NOT NULL,
  total       BIGINT NOT NULL,
  file_ref    TEXT NOT NULL,                       -- nama file / tautan Drive
  file_key    TEXT,                                -- berkas di storage (opsional)
  deadline    TEXT,
  note        TEXT,
  status      TEXT NOT NULL CHECK (status IN ('cek','revisi','bayar','antrian','produksi','curing','qc','packing','siap','selesai','ditolak')),
  stage       TEXT NOT NULL CHECK (stage IN ('dtf','subp','cal')),
  priority    BIGINT NOT NULL DEFAULT 0,
  issue       TEXT,
  rework_m    DOUBLE PRECISION,
  process     TEXT,
  receiver    TEXT,
  created_by  TEXT NOT NULL,
  created_at  BIGINT NOT NULL,
  approved_at BIGINT,
  started_at  BIGINT,
  finished_at BIGINT,
  qc_by       TEXT,
  handed_at   BIGINT,
  request_key TEXT UNIQUE                          -- cegah order ganda saat dikirim ulang
);
CREATE INDEX idx_orders_status ON orders(status);
-- Satu mesin hanya boleh mengerjakan satu order pada satu waktu.
CREATE UNIQUE INDEX idx_one_job_per_machine ON orders(stage) WHERE status IN ('produksi','curing');

CREATE TABLE payments (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    BIGINT NOT NULL REFERENCES orders(id),
  amount      BIGINT NOT NULL CHECK (amount > 0),
  method      TEXT NOT NULL CHECK (method IN ('Transfer','QRIS','Tunai')),
  by_user     TEXT NOT NULL,
  at          BIGINT NOT NULL,
  request_key TEXT UNIQUE
);
CREATE INDEX idx_payments_order ON payments(order_id);

CREATE TABLE skus (
  code      TEXT PRIMARY KEY,
  name      TEXT NOT NULL,
  svc       TEXT NOT NULL CHECK (svc IN ('dtf','sub')),
  unit      TEXT NOT NULL,
  stock     DOUBLE PRECISION NOT NULL DEFAULT 0,
  min_stock DOUBLE PRECISION NOT NULL DEFAULT 0,
  use_per_m DOUBLE PRECISION,                      -- NULL = belum diukur, tidak dipotong otomatis
  machine   TEXT NOT NULL CHECK (machine IN ('dtf','subp','cal'))
);

CREATE TABLE stock_ledger (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku_code TEXT NOT NULL REFERENCES skus(code),
  type     TEXT NOT NULL,
  qty      DOUBLE PRECISION NOT NULL,
  ref      TEXT NOT NULL,
  by_user  TEXT NOT NULL,
  at       BIGINT NOT NULL
);

CREATE TABLE qc_reports (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  machine     TEXT NOT NULL CHECK (machine IN ('dtf','subp','cal')),
  day         TEXT NOT NULL,                       -- tanggal kerja WITA
  answers     TEXT NOT NULL,                       -- JSON jawaban checklist
  ng          TEXT NOT NULL,                       -- JSON butir tidak sesuai
  note        TEXT,
  action      TEXT,
  photos      TEXT NOT NULL,                       -- JSON [{label,key}]
  status      TEXT NOT NULL CHECK (status IN ('menunggu','siap','tahan')),
  by_user     TEXT NOT NULL,
  at          BIGINT NOT NULL,
  approved_by TEXT,
  approved_at BIGINT,
  leader_note TEXT
);
CREATE INDEX idx_qc_day ON qc_reports(day, machine);

CREATE TABLE logs (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no TEXT NOT NULL,
  type     TEXT NOT NULL CHECK (type IN ('Loss Sales','Reject')),
  reason   TEXT NOT NULL,
  value    BIGINT,
  counted  BIGINT NOT NULL DEFAULT 0,
  by_user  TEXT NOT NULL,
  at       BIGINT NOT NULL
);

CREATE TABLE files (
  key          TEXT PRIMARY KEY,
  kind         TEXT NOT NULL CHECK (kind IN ('artwork','qc_photo')),
  file_name    TEXT NOT NULL,
  content_type TEXT NOT NULL,
  size_bytes   BIGINT NOT NULL,
  uploaded_by  BIGINT NOT NULL REFERENCES users(id),
  uploaded_at  BIGINT NOT NULL,
  confirmed    BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE audit_log (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at      BIGINT NOT NULL,
  user_id BIGINT,
  action  TEXT NOT NULL,
  entity  TEXT,
  entity_id TEXT,
  detail  TEXT
);

